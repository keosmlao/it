    await c.query(
      `insert into it.kb_articles
         (title, body, category_code, keywords, author_employee_id)
       values ($1::varchar, $2::text, $3::varchar, $4::varchar, $5::int)`,
      [a.title, a.body, a.category, a.keywords, author.employee_id]
    )
    console.log(`  ✓ ເພີ່ມ [${a.category}] ${a.title}`)
